from __future__ import annotations

from typing import TYPE_CHECKING

import pytest
from pyqwest import Client
from pyqwest.testing import ASGITransport

from connectrpc.method import IdempotencyLevel, MethodInfo, StreamType
from connectrpc.server import ConnectASGIApplication, ConnectWSGIApplication, Endpoint

from .connectrpc.example.haberdasher_connect import Haberdasher, HaberdasherClient
from .connectrpc.example.haberdasher_pb import Hat, Size

if TYPE_CHECKING:
    from connectrpc.request import RequestContext

_SERVICE_NAME = "connectrpc.example.Haberdasher"


class SimpleHaberdasher(Haberdasher):
    async def make_hat(self, request: Size, _ctx: RequestContext[Size, Hat], /) -> Hat:
        return Hat(size=request.inches, color="blue")


@pytest.mark.anyio
async def test_deprecated_endpoints_still_supported() -> None:
    """Code generated by older plugin versions passes endpoints and overrides path."""

    class LegacyApplication(ConnectASGIApplication[SimpleHaberdasher]):
        def __init__(self, service: SimpleHaberdasher) -> None:
            super().__init__(  # ty: ignore[deprecated]
                service=service,
                endpoints=lambda svc: {
                    f"/{_SERVICE_NAME}/MakeHat": Endpoint.unary(
                        method=MethodInfo(
                            name="MakeHat",
                            service_name=_SERVICE_NAME,
                            input=Size,
                            output=Hat,
                            idempotency_level=IdempotencyLevel.NO_SIDE_EFFECTS,
                            stream_type=StreamType.UNARY,
                        ),
                        function=svc.make_hat,
                    )
                },
            )

        @property
        def path(self) -> str:
            return f"/{_SERVICE_NAME}"

    app = LegacyApplication(SimpleHaberdasher())
    async with (
        ASGITransport(app) as transport,
        HaberdasherClient("http://localhost", http_client=Client(transport)) as client,
    ):
        assert await client.make_hat(Size(inches=10)) == Hat(size=10, color="blue")


def test_path_requires_override_with_endpoints() -> None:
    app = ConnectASGIApplication(  # ty: ignore[deprecated]
        service=SimpleHaberdasher(), endpoints=lambda _: {}
    )
    with pytest.raises(NotImplementedError, match="path must be overridden"):
        _ = app.path
    sync_app = ConnectWSGIApplication(endpoints={})  # ty: ignore[deprecated]
    with pytest.raises(NotImplementedError, match="path must be overridden"):
        _ = sync_app.path


def test_requires_exactly_one_of_desc_or_endpoints() -> None:
    with pytest.raises(ValueError, match="one of desc or endpoints must be provided"):
        ConnectASGIApplication(service=SimpleHaberdasher())  # ty: ignore[no-matching-overload]
    with pytest.raises(ValueError, match="only one of desc or endpoints"):
        ConnectASGIApplication(  # ty: ignore[no-matching-overload]
            service=SimpleHaberdasher(), desc=Haberdasher.desc(), endpoints=lambda _: {}
        )
    with pytest.raises(ValueError, match="service must be provided with desc"):
        ConnectWSGIApplication(desc=Haberdasher.desc())  # ty: ignore[no-matching-overload]
